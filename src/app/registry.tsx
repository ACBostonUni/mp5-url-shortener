"use client";

// I learned that this file is necessary to have a fully bug free site

// This ca// Next.js renders the application on the server,
// when someone visits the web, Next.js generates the HTML before sending it to the browser
// The HTML is sent to the browser, but the CSS hasn't been inserted yet.
// Then the J.S loads, styled components is initialized on the client and the styled get inserted
// This causes a flash of unstyled content (Which is what my MP4 had) Website briefly appears without its styling before the CSS is applied.


// This is why I need a registry and why my previous website was a tad buggy.
// The regisrty creates a stylesheet that collects the CSS generated by the styled components
// during server rendering.

// When it sends the HTML to the browser, it tells Next.js to insert the CSS collected by the styled components

// Once the application is running in the browser, the styled components handle injecting as usual.

// The registry's job is primarily to ensure that the initial server-rendered styles are collected and delivered correctly.
// The client-side styled-components runtime handles subsequent changes.



import { useState } from "react";
import { useServerInsertedHTML } from "next/navigation";
import { ServerStyleSheet, StyleSheetManager } from "styled-components";

export default function StyledComponentsRegistry({
                                                     children,
                                                 }: {
    children: React.ReactNode;
}) {
    const [sheet] = useState(() => new ServerStyleSheet());

    useServerInsertedHTML(() => {
        const styles = sheet.getStyleElement();
        sheet.instance.clearTag();
        return <>{styles}</>;
    });

    if (typeof window !== "undefined") {
        return <>{children}</>;
    }

    return (
        <StyleSheetManager sheet={sheet.instance}>
            {children}
        </StyleSheetManager>
    );
}